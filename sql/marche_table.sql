-- Creation de la table de travail ogmarche.marche (fiches a valider), equivalente a
-- l'entite App\Entity\Marche : resultat cumule des migrations Doctrine. A utiliser pour
-- recreer la table a la main (ex. apres un DROP). Rejouable (IF NOT EXISTS).
-- Ordre : sql/schema.sql (table brute) -> migrations Doctrine -> ce script si marche manque
-- -> sql/marche.sql (alimentation depuis marche_geocode_raw).

CREATE SCHEMA IF NOT EXISTS ogmarche;

CREATE TABLE IF NOT EXISTS ogmarche.marche (
    id                     INT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    raw_row_id             BIGINT DEFAULT NULL,                 -- lien vers marche_geocode_raw.row_id
    unique_id              VARCHAR(40) DEFAULT NULL,
    id_marche              INT DEFAULT NULL,
    denomination_f         VARCHAR(100) DEFAULT NULL,
    denomination_normalise VARCHAR(100) DEFAULT NULL,
    code_dep               VARCHAR(3) NOT NULL,
    num_voie               VARCHAR(10) DEFAULT NULL,
    type_voie              VARCHAR(20) DEFAULT NULL,
    nom_voie               VARCHAR(100) DEFAULT NULL,
    code_postal            VARCHAR(5) DEFAULT NULL,
    commune                VARCHAR(100) NOT NULL,
    code_insee             VARCHAR(5) DEFAULT NULL,
    longitude              DOUBLE PRECISION DEFAULT NULL,
    latitude               DOUBLE PRECISION DEFAULT NULL,
    precision              VARCHAR(20) DEFAULT NULL,
    id_ban                 VARCHAR(20) DEFAULT NULL,
    produits               TEXT DEFAULT NULL,
    specificite            VARCHAR(255) DEFAULT NULL,
    action_type            VARCHAR(30) DEFAULT 'EXISTANCE_AVALIDER' NOT NULL,
    horaire_brut           VARCHAR(255) DEFAULT NULL,
    jours_txt              VARCHAR(100) DEFAULT NULL,
    heure_debut            TIME(0) WITHOUT TIME ZONE DEFAULT NULL,
    heure_fin              TIME(0) WITHOUT TIME ZONE DEFAULT NULL,
    toute_annee            BOOLEAN DEFAULT NULL,
    mois_debut             VARCHAR(10) DEFAULT NULL,
    mois_fin               VARCHAR(10) DEFAULT NULL,
    codens                 VARCHAR(30) DEFAULT NULL,            -- groupe de doublons "id_<dep>_<n>"
    nom_ok                 BOOLEAN DEFAULT false NOT NULL,
    adresse_ok             BOOLEAN DEFAULT false NOT NULL,
    produits_ok            BOOLEAN DEFAULT false NOT NULL,
    horaire_ok             BOOLEAN DEFAULT false NOT NULL,
    garde                  BOOLEAN DEFAULT NULL,                -- decision garder / ne pas garder
    traite                 BOOLEAN DEFAULT false NOT NULL,
    rappel                 BOOLEAN DEFAULT false NOT NULL,
    validated_by           INT DEFAULT NULL,                    -- public.user.id (pas de FK : autre schema)
    date_de_validation     TIMESTAMP(0) WITHOUT TIME ZONE DEFAULT NULL,
    PRIMARY KEY (id)
);

CREATE INDEX IF NOT EXISTS idx_marche_dep_insee ON ogmarche.marche (code_dep, code_insee);
CREATE INDEX IF NOT EXISTS idx_marche_codens    ON ogmarche.marche (codens);
